@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ArchitectureDocsScreen(
    onNavigateBack: () -> Unit,
    modifier: Modifier = Modifier
) {
    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Text(
                        text = stringResource(R.string.arch_title),
                        style = MaterialTheme.typography.titleLarge,
                        fontWeight = FontWeight.Bold
                    )
                },
                navigationIcon = {
                    IconButton(onClick = onNavigateBack) {
                        Icon(
                            imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                            contentDescription = stringResource(R.string.back)
                        )
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.background
                )
            )
        },
        modifier = modifier.fillMaxSize()
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
                .padding(horizontal = 20.dp)
                .verticalScroll(rememberScrollState())
        ) {
            Spacer(modifier = Modifier.height(12.dp))

            DocCard(
                icon = Icons.Default.Security,
                title = stringResource(R.string.arch_overview_title),
                content = stringResource(R.string.arch_overview_desc)
            )

            Spacer(modifier = Modifier.height(14.dp))

            DocCard(
                icon = Icons.Default.BusinessCenter,
                title = stringResource(R.string.arch_strategy_work_profile_title),
                content = stringResource(R.string.arch_strategy_work_profile_desc)
            )

            Spacer(modifier = Modifier.height(14.dp))

            DocCard(
                icon = Icons.Default.Layers,
                title = stringResource(R.string.arch_strategy_container_title),
                content = stringResource(R.string.arch_strategy_container_desc)
            )

            Spacer(modifier = Modifier.height(14.dp))

            DocCard(
                icon = Icons.Default.Code,
                title = stringResource(R.string.arch_chatgpt_case_title),
                content = stringResource(R.string.arch_chatgpt_case_desc)
            )

            Spacer(modifier = Modifier.height(14.dp))

            DocCard(
                icon = Icons.Default.Architecture,
                title = stringResource(R.string.arch_constraints_title),
                content = stringResource(R.string.arch_constraints_desc)
            )

            Spacer(modifier = Modifier.height(32.dp))
        }
    }
}

@Composable
fun DocCard(
    icon: ImageVector,
    title: String,
    content: String
) {
    Card(
        shape = RoundedCornerShape(18.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
        elevation = CardDefaults.cardElevation(defaultElevation = 1.dp),
        modifier = Modifier.fillMaxWidth()
    ) {
        Column(modifier = Modifier.padding(18.dp)) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Box(
                    modifier = Modifier
                        .size(36.dp)
                        .clip(CircleShape)
                        .background(MaterialTheme.colorScheme.primaryContainer),
                    contentAlignment = Alignment.Center
                ) {
                    Icon(
                        imageVector = icon,
                        contentDescription = null,
                        tint = MaterialTheme.colorScheme.primary,
                        modifier = Modifier.size(20.dp)
                    )
                }
                Spacer(modifier = Modifier.width(12.dp))
                Text(
                    text = title,
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold
                )
            }
            Spacer(modifier = Modifier.height(10.dp))
            Text(
                text = content,
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                lineHeight = 22.sp
            )
        }
    }
}
